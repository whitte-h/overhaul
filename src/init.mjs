// `overhaul setup`: the first config.yaml and env of an installation, only when they are missing
// (what install.sh, `service install`, `update` and Homebrew run; `overhaul init` is the project
// wizard, src/wizard.mjs). And `overhaul paths`: where everything is.
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import YAML from "yaml";
import { assetText } from "./assets.mjs";
import { resolvePaths, expandHomeIn } from "./paths.mjs";

const SAMPLE = `
# Add a project: run "overhaul init" in its folder (a repo, or a folder with several repos).
# Or by hand: replace "projects: {}" above, then restart the hub (overhaul service restart).
# config.example.yaml in the repo has every option, commented. A minimal one:
#
# projects:
#   personal:
#     name: Personal
#     repo: ~/code/personal/MyRepo
#     tracker:
#       type: kanban-md
#       dir: ~/code/personal/MyRepo/kanban
#     runtime: { command: claude }   # one agent per ticket, in tmux
`;

// config.example.yaml's general settings, loopback only, no desktop helper, this machine's time
// zone and no projects yet. No data_dir: the data stays in the installation's folder.
export function standaloneConfig(exampleText, timezone, dataDir = null) {
  const example = YAML.parse(exampleText) ?? {};
  const cfg = {
    version: 2,
    port: example.port ?? 7420,
    bind: ["127.0.0.1"], // loopback only: no LAN or VPN (and no macOS Local Network prompt)
    timezone: timezone || "UTC",
    ...(dataDir ? { data_dir: dataDir } : {}),
    terminal: example.terminal ?? "tmux",
    defaults: example.defaults ?? {},
    projects: {},
  };
  return `# Overhaul, config v2 (generated by overhaul setup from config.example.yaml).\n${YAML.stringify(cfg)}${SAMPLE}`;
}

export const randomToken = () => crypto.randomBytes(32).toString("hex");

// Creates what is missing: the folder (0700), config.yaml, env (0600) with HUB_AGENT_TOKEN.
export function setup({ env = process.env, userHome, log = () => {} } = {}) {
  const P = resolvePaths(env, userHome);
  fs.mkdirSync(P.configDir, { recursive: true, mode: 0o700 });
  if (P.configDir === P.home) fs.chmodSync(P.home, 0o700);
  if (fs.existsSync(P.config) || fs.existsSync(path.join(P.configDir, "config.json"))) log(`Config: ${P.config} ya existe, no la toco`);
  else {
    const tz = Intl.DateTimeFormat().resolvedOptions().timeZone;
    fs.writeFileSync(P.config, standaloneConfig(assetText("config.example.yaml"), tz), { mode: 0o600 });
    log(`Config: creé ${P.config} (sin proyectos todavía)`);
  }
  if (!fs.existsSync(P.env)) {
    fs.writeFileSync(P.env, "# Overhaul secrets (600). Tracker tokens go here too, named by *_env in config.yaml.\n", { mode: 0o600 });
    log(`Env: creé ${P.env}`);
  }
  fs.chmodSync(P.env, 0o600);
  const text = fs.readFileSync(P.env, "utf8");
  if (!/^HUB_AGENT_TOKEN=.{24,}$/m.test(text)) {
    fs.appendFileSync(P.env, `${text && !text.endsWith("\n") ? "\n" : ""}HUB_AGENT_TOKEN=${randomToken()}\n`);
    log("Env: agregué HUB_AGENT_TOKEN");
  }
  return P;
}
export const init = setup; // before v0.2.1

// The paths plus the data folder config.yaml actually uses.
export function describePaths({ env = process.env, userHome } = {}) {
  const P = resolvePaths(env, userHome);
  let dataDir = P.dataDir;
  try {
    const raw = YAML.parse(fs.readFileSync(P.config, "utf8")) ?? {};
    const v = raw.data_dir ?? raw.dataDir;
    if (v) dataDir = path.resolve(expandHomeIn(userHome ?? env.HOME)(String(v)));
  } catch {}
  return { home: P.home, mode: P.mode, config: P.config, env: P.env, db: path.join(dataDir, "overhaul.db"), dataDir, logs: P.logs, bin: P.bin, backups: P.backups };
}

// The hub's port from config.yaml (7420 by default), to tell whether it is running.
export function configPort(file) {
  try {
    return Number((YAML.parse(fs.readFileSync(file, "utf8")) ?? {}).port) || 7420;
  } catch {
    return 7420;
  }
}
export const hubPort = ({ env = process.env, userHome } = {}) => configPort(resolvePaths(env, userHome).config);

