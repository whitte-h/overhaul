#!/usr/bin/env node
// First config.yaml (v2) for a standalone Overhaul (install.sh runs this only when there is none):
// config.example.yaml's general settings, loopback only, no desktop helper, this machine's time
// zone and no projects yet (every project you add runs here unless it says `host:`).
//   node deploy/standalone/config.mjs [config.example.yaml] > ~/.config/overhaul/config.yaml
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import YAML from "yaml";
import { defaultDataDir } from "../../src/env.mjs";
import { tilde } from "../../src/configfile.mjs";

const SAMPLE = `
# Replace "projects: {}" above with your projects, then restart the hub (see README).
# config.example.yaml in the repo has every option, commented. A minimal one:
#
# projects:
#   personal:
#     name: Personal
#     repo: ~/code/personal/MyRepo
#     tracker:
#       type: kanban-md
#       dir: ~/code/personal/MyRepo/kanban
#     runtime: { command: claude }   # one agent per ticket, in tmux
`;

// data_dir is written out, so the hub never switches folders later on its own.
export function standaloneConfig(exampleText, timezone, dataDir = "~/.local/share/overhaul") {
  const example = YAML.parse(exampleText) ?? {};
  const cfg = {
    version: 2,
    port: example.port ?? 7420,
    bind: ["127.0.0.1"], // loopback only: no LAN or VPN (and no macOS Local Network prompt)
    timezone: timezone || "UTC",
    data_dir: dataDir,
    terminal: example.terminal ?? "tmux",
    defaults: example.defaults ?? {},
    projects: {},
  };
  return `# Overhaul standalone, config v2 (generated by install.sh from config.example.yaml).\n${YAML.stringify(cfg)}${SAMPLE}`;
}

if (process.argv[1] && fs.realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
  const example = process.argv[2] ?? path.join(root, "config.example.yaml");
  // The pre-rename data folder when it is the only one, else ~/.local/share/overhaul.
  process.stdout.write(standaloneConfig(fs.readFileSync(example, "utf8"), Intl.DateTimeFormat().resolvedOptions().timeZone, tilde(defaultDataDir())));
}
